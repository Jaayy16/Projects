    /**
     * This button adds all the inputs to variables, 
     * clears the text fields and checks to make sure all inputs are 
     * valid before adding them to functions
     */
    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        String inpName = txtName.getText();
        String inpSurname = txtSurname.getText();
        String inpAge = txtAge.getText();
        String inpDate = txtDate.getText();

        txtName.setText("");
        txtSurname.setText("");
        txtAge.setText("");
        txtDate.setText("");
        
        boolean valid = true;
        
        if (inpName.isEmpty())
        {
            JOptionPane.showMessageDialog(null, "Error: please input a name", "Error", JOptionPane.ERROR_MESSAGE);
            valid = false;
        }
        
        if(inpSurname.isEmpty())
        {
            JOptionPane.showMessageDialog(null, "Error: please input a surname", "Error", JOptionPane.ERROR_MESSAGE);
            valid = false;
        }
        
        if(!intValidate(inpAge)){
            valid = false;
        }
        
        if(!dateValidate(inpDate)){
            valid = false;
        }
        
        if(valid){
            String Entry = ""; 
            Entry += inpName + " " + inpSurname + " | " + "Age: " + Integer.parseInt(inpAge) + " | " + "Date: " + LocalDate.parse(inpDate);
            StudentRecords.add(Entry);
        }
        
    }//GEN-LAST:event_btnAddActionPerformed
    
    /**
     * This method checks that the age is between 10 and 100, 
     * that the text field is not empty and also a valid integer
     */
    private boolean intValidate(String intInput){
        
        if(intInput == null || intInput.trim().isEmpty())
        {
            JOptionPane.showMessageDialog(null, "Error: Age must be filled", "Error", JOptionPane.ERROR_MESSAGE);
            return false;
        }
        
        try
        {
            int ageInput = Integer.parseInt(intInput.trim());
            if (ageInput <= 10 || ageInput >= 100)
            {
                JOptionPane.showMessageDialog(null, "Error: Age must be a valid number", "Error", JOptionPane.ERROR_MESSAGE);
            }
            return true;
 
        }
        catch(NumberFormatException e)
        {
            JOptionPane.showMessageDialog(null, "Error: Age must be a valid number", "Error", JOptionPane.ERROR_MESSAGE);
            return false;
        }
    }
    
    /**
     * This method checks that the date was inputted in YYYY-MM-DD format into the
     * text field if it wasn't it returns an error but if it is it returns true
     * allowing the validation to pass
    */
    private boolean dateValidate(String inpDate) {
        try {
            DateTimeFormatter format = DateTimeFormatter.ofPattern("yyyy-MM-dd");
        
            LocalDate.parse(inpDate, format);
        
            return true;
            
        } catch (DateTimeParseException e) {
            JOptionPane.showMessageDialog(null, "Error: Date must be in YYYY-MM-DD", "Error", JOptionPane.ERROR_MESSAGE);    
            return false;
        }   
    }
    
