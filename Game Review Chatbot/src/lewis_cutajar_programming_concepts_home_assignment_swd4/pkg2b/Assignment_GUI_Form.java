    /**
     * This method updates the text area to display in information inputted by the
     * user in the style of
     * ' Name Surname | Age | Date '
     */
    private void UpdateTaskDisplay(){   
        
        String fullList = "";
        for (int i = 0; i < StudentRecords.size(); i++) {
            fullList += StudentRecords.get(i) + "\n";
        }
        txtDisplay.setText(fullList);
    }
    
    /**
     * This code saves the file under the name ' Students.txt '
     * If a file under the same name exists it deletes that file
     * and saves the new entries under the same name it saves the entries in the
     * style of ' Name Surname | Age | Date ' and tell the user ' Records saved successfully '
     * if something goes wrong during the saving of the file it gives an error saying 'Error saving to file '
     */
    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        Path path = Paths.get("Students.txt");
        
        try{
            if (Files.exists(path)){
                Files.delete(path);
                System.out.println("File deleted successfully!");
            } else {
                System.out.println("File does not exist!");
            }
        } catch (IOException e){
            System.out.println("An error occured while deleting " + e.getMessage());
        }
        
        try (BufferedWriter writer = new BufferedWriter(new FileWriter("Students.txt"))){
            for (int i = 0; i < StudentRecords.size(); i++){
                writer.write(StudentRecords.get(i));
                writer.newLine();
            }
            JOptionPane.showMessageDialog(null, "Records saved successfully!");
        } catch (IOException e) {
            JOptionPane.showMessageDialog(null, "Error saving to file: " + e.getMessage());
        }
    }//GEN-LAST:event_btnSaveActionPerformed

